// Library popup: expand, 8% border, close via X / Esc / backdrop.   node tests/libpopup.mjs
import { _electron as electron } from 'playwright';
import fs from 'fs'; import os from 'os'; import path from 'path';
import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'tests', 'out'); fs.mkdirSync(OUT, { recursive: true });
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'ms-lp-'));
const fails = []; const check = (c, m) => { console.log(c ? '   ✓' : '   ✗', m); if (!c) fails.push(m); };
const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => k !== 'ELECTRON_RUN_AS_NODE'));
Object.assign(env, { MATHSTUDIO_NO_AUTOSAVE: '1', MATHSTUDIO_HIDDEN: '1', MATHSTUDIO_DATA: path.join(TMP, 'data') });
const app = await electron.launch({ args: [ROOT], env, cwd: ROOT });
const win = await app.firstWindow();
await win.setViewportSize({ width: 1600, height: 950 });
await win.waitForSelector('.lib-card', { timeout: 90000 });
const box = () => win.evaluate(() => { const r = document.querySelector('.library').getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, iw: innerWidth, ih: innerHeight }; });
const isFull = () => win.evaluate(() => document.querySelector('.library').classList.contains('full'));
const open = async () => { await win.click('[data-testid=library-expand]'); await win.waitForSelector('.library.full'); };
await open();
const b = await box();
check(Math.abs(b.x - b.iw * 0.08) < 2 && Math.abs(b.y - b.ih * 0.08) < 2, `8% margins left/top (${b.x.toFixed(0)},${b.y.toFixed(0)})`);
check(Math.abs(b.iw - b.x - b.w - b.iw * 0.08) < 2 && Math.abs(b.ih - b.y - b.h - b.ih * 0.08) < 2, '8% margins right/bottom');
const cb = await win.locator('[data-testid=library-close]').boundingBox();
check(cb && cb.x > b.x + b.w - 50 && cb.y < b.y + 50, 'close button at top-right, beside the search');
await win.screenshot({ path: path.join(OUT, 'libpopup.png') });
await win.click('[data-testid=library-close]'); check(!(await isFull()), 'X closes');
await open(); await win.keyboard.press('Escape'); check(!(await isFull()), 'Esc closes');
await open(); await win.mouse.click(10, 400); check(!(await isFull()), 'border click closes');
check(await win.locator('.library .panel-head').count() === 0, 'no "Library" title');
await open(); check(await isFull(), 'expand button opens');
await win.mouse.click(b.x + 200, b.y + 200); check(await isFull(), 'click inside stays open');
await app.close();
console.log(fails.length ? `FAILED ${fails.length}` : 'ALL PASS'); process.exit(fails.length ? 1 : 0);
