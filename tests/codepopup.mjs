// Library popup: expand, 8% border, close via X / Esc / backdrop.   node tests/codepopup.mjs
import { _electron as electron } from 'playwright';
import fs from 'fs'; import os from 'os'; import path from 'path';
import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'tests', 'out'); fs.mkdirSync(OUT, { recursive: true });
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'ms-lp-'));
const fails = []; const check = (c, m) => { console.log(c ? '   ✓' : '   ✗', m); if (!c) fails.push(m); };
const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => k !== 'ELECTRON_RUN_AS_NODE'));
Object.assign(env, { MATHSTUDIO_NO_AUTOSAVE: '1', MATHSTUDIO_HIDDEN: '1', MATHSTUDIO_DATA: path.join(TMP, 'data') });
const app = await electron.launch({ args: [ROOT], env, cwd: ROOT });
const win = await app.firstWindow();
await win.setViewportSize({ width: 1600, height: 950 });
await win.waitForSelector('.lib-card', { timeout: 90000 });
await win.click('[data-testid="load-example"]'); await win.waitForTimeout(2500);
const codeBtn = 'button[title^="Show the generated ManimGL code"]';
const open = async () => { await win.click(codeBtn); await win.waitForSelector('.code-panel.full'); };
const isOpen = () => win.evaluate(() => !!document.querySelector('.code-panel'));
check(!(await isOpen()), 'no code div before clicking Code');
await open();
const b = await win.evaluate(() => { const r = document.querySelector('.code-panel').getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, iw: innerWidth, ih: innerHeight }; });
check(Math.abs(b.x - b.iw * 0.08) < 2 && Math.abs(b.y - b.ih * 0.08) < 2, `8% margins left/top (${b.x.toFixed(0)},${b.y.toFixed(0)})`);
check(Math.abs(b.iw - b.x - b.w - b.iw * 0.08) < 2 && Math.abs(b.ih - b.y - b.h - b.ih * 0.08) < 2, '8% margins right/bottom');
await win.waitForFunction(() => document.querySelector('.cm-content')?.textContent.includes('MainScene'), null, { timeout: 8000 }).then(() => check(true, 'scene code shown'), () => check(false, 'scene code shown'));
await win.screenshot({ path: path.join(OUT, 'codepopup.png') });
await win.click('[data-testid=code-close]'); check(!(await isOpen()), 'X closes');
await open(); await win.keyboard.press('Escape'); check(!(await isOpen()), 'Esc closes');
await open(); await win.mouse.click(10, 400); check(!(await isOpen()), 'border click closes');
await open(); await win.mouse.click(b.x + 200, b.y + 200); check(await isOpen(), 'click inside stays open');
await win.waitForTimeout(4000); check(await isOpen(), 'still open after 4s');
await app.close();
console.log(fails.length ? `FAILED ${fails.length}` : 'ALL PASS'); process.exit(fails.length ? 1 : 0);
